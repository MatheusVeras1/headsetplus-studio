def generate_i18n_js():
    js_content = "/* ==========================================================================\n"
    js_content += "   HeadsetPlus Studio — Motor de Internacionalização & Idiomas (i18n)\n"
    js_content += "   Created by Matheus Veras • Source-Available Proprietary (Ver LICENSE.md)\n"
    js_content += "   ========================================================================== */\n\n"
    js_content += "const I18N_TRANSLATIONS = " + json.dumps(TRANSLATIONS, indent=2, ensure_ascii=False) + ";\n\n"
    
    js_content += """
function detectBrowserLanguage() {
  const navLangs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || navigator.userLanguage || ""];
  for (const nl of navLangs) {
    if (!nl) continue;
    const lower = nl.toLowerCase();
    if (lower.startsWith("pt")) return "pt-BR";
    if (lower.startsWith("ja")) return "ja-JP";
    if (lower.startsWith("es")) return "es-ES";
    if (lower.startsWith("de")) return "de-DE";
    if (lower.startsWith("zh")) return "zh-CN";
    if (lower.startsWith("fr")) return "fr-FR";
    if (lower.startsWith("en")) return "en-US";
  }
  return "en-US";
}

function getInitialLanguage() {
  const saved = localStorage.getItem("sony_lang");
  if (saved && I18N_TRANSLATIONS[saved]) {
    return saved;
  }
  if (window.__systemLanguage && I18N_TRANSLATIONS[window.__systemLanguage]) {
    return window.__systemLanguage;
  }
  return detectBrowserLanguage();
}

let currentAppLanguage = getInitialLanguage();

function getTranslation(keyPath, lang = currentAppLanguage) {
  const dict = I18N_TRANSLATIONS[lang] || I18N_TRANSLATIONS["en-US"] || I18N_TRANSLATIONS["pt-BR"];
  const keys = keyPath.split(".");
  let cur = dict;
  for (const k of keys) {
    if (cur && typeof cur === "object" && k in cur) {
      cur = cur[k];
    } else {
      let fallback = I18N_TRANSLATIONS["en-US"] || I18N_TRANSLATIONS["pt-BR"];
      for (const fk of keys) {
        if (fallback && typeof fallback === "object" && fk in fallback) {
          fallback = fallback[fk];
        } else {
          return keyPath;
        }
      }
      return typeof fallback === "string" ? fallback : keyPath;
    }
  }
  return typeof cur === "string" ? cur : keyPath;
}

function setAppLanguage(lang, skipBackendSync = false) {
  if (!I18N_TRANSLATIONS[lang]) return;
  currentAppLanguage = lang;
  localStorage.setItem("sony_lang", lang);

  // 1. Atualizar todos os elementos com data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const trans = getTranslation(key, lang);
      if (trans && trans !== key) {
        el.textContent = trans;
      }
    }
  });

  // 2. Atualizar data-tooltip com data-i18n-tooltip
  document.querySelectorAll("[data-i18n-tooltip]").forEach((el) => {
    const key = el.getAttribute("data-i18n-tooltip");
    if (key) {
      const trans = getTranslation(key, lang);
      if (trans && trans !== key) {
        el.setAttribute("data-tooltip", trans);
      }
    }
  });

  // 3. Atualizar title com data-i18n-title
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      const trans = getTranslation(key, lang);
      if (trans && trans !== key) {
        el.setAttribute("title", trans);
      }
    }
  });

  // 4. Atualizar placeholders com data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      const trans = getTranslation(key, lang);
      if (trans && trans !== key) {
        el.setAttribute("placeholder", trans);
      }
    }
  });

  // 5. Atualizar pílulas de idioma ativas na grade de configurações
  document.querySelectorAll(".lang-card-pill").forEach((pill) => {
    pill.classList.toggle("active", pill.getAttribute("data-lang") === lang);
  });

  // 6. Atualizar menus dinâmicos se existirem
  if (typeof renderDeviceSelectorItems === "function") {
    renderDeviceSelectorItems();
  }

  // 7. Sincronizar com Python backend se disponível
  if (!skipBackendSync && window.pywebview && window.pywebview.api && window.pywebview.api.set_language) {
    window.pywebview.api.set_language(lang).catch(() => {});
  }
}

// Inicialização imediata ao carregar o script
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => {
    setAppLanguage(currentAppLanguage, true);
  });
} else {
  setAppLanguage(currentAppLanguage, true);
}

window.I18N_TRANSLATIONS = I18N_TRANSLATIONS;
window.getTranslation = getTranslation;
window.setAppLanguage = setAppLanguage;
window.getInitialLanguage = getInitialLanguage;
window.detectBrowserLanguage = detectBrowserLanguage;
"""
    with open("ui/i18n.js", "w", encoding="utf-8") as f:
        f.write(js_content)
    print("ui/i18n.js generated successfully! Size:", len(js_content), "bytes.")

